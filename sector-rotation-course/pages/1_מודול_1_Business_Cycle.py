# ---------------------------- NBER ----------------------------

st.markdown("## 🏛️ ההגדרה הרשמית של מיתון – NBER")

st.markdown(
    """
ה-**National Bureau of Economic Research** (NBER) הוא הגוף הרשמי שמתארך מיתונים בארה"ב.
ועדת התארוך שלהם (Business Cycle Dating Committee) מגדירה מיתון כ:

> "ירידה משמעותית בפעילות הכלכלית, **מפושטת על פני המשק**, שנמשכת **יותר מכמה חודשים בודדים**"

הם בוחנים **6 אינדיקטורים מתואמים (coincident)**: (1) תוצר ריאלי, (2) הכנסה ריאלית
ללא העברות, (3) תעסוקה (Nonfarm payrolls), (4) צריכה ריאלית, (5) מכירות סיטונאיות-קמעונאיות
ריאליות, (6) ייצור תעשייתי.

> ⚠️ **מיתוס נפוץ:** "מיתון = שני רבעונים רצופים של GDP שלילי". זה **לא** ההגדרה של NBER.
> GDP הוא רק קלט אחד מתוך 6. ב-2022 ארה"ב חוותה שני רבעונים שליליים ברצף אבל NBER לא
> הכריזה על מיתון, כי תעסוקה והכנסה המשיכו לעלות.

**חשוב לדעת:** NBER מכריזה על מיתון **רטרואקטיבית** – לפעמים שנה או יותר אחרי שהוא התחיל
(למשל, מיתון 2008 הוכרז רק בדצמבר 2008, 12 חודשים אחרי שהתחיל בדצמבר 2007). לכן
**אסור להסתמך עליה כאיתות בזמן אמת** – צריך לבנות תהליך זיהוי משלך מהאינדיקטורים המובילים.
"""
)

with st.expander("📖 העמקה: Leading vs Coincident vs Lagging"):
    st.markdown(
        """
- **מובילים (Leading):** עקום תשואות, רישיוני בנייה, PMI New Orders, ציפיות צרכן, S&P 500, דרישות אבטלה ראשוניות.
- **מתואמים (Coincident):** GDP, תעסוקה (payrolls), ייצור תעשייתי, הכנסה ריאלית – 6 הרכיבים של NBER.
- **מפגרים (Lagging):** שיעור אבטלה (UNRATE), CPI core, יחס מלאים-למכירות, יתרות אשראי צרכני.

**הכלל לסקטור-רוטייטור:** סחר על מה ש**מוביל**, אמת מול ה**מתואמים**, התעלם מ**מפגרים** לצרכי תזמון.
        """
    )


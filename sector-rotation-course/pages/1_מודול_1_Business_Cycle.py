# ---------------------------- YIELD CURVE ----------------------------

st.markdown("## 📉 עקום התשואות כמנבא מיתון")

st.markdown(
    """
**T10Y2Y** הוא ההפרש בין תשואת אג"ח ממשלת ארה"ב ל-10 שנים לבין תשואת אג"ח ל-2 שנים.
בדרך כלל ההפרש חיובי (עקום עולה) – משקיעים דורשים פיצוי על הסיכון להחזיק אג"ח ארוך יותר.
כש-T10Y2Y הופך **שלילי** (העקום מתהפך, inversion), זה היסטורית סימן אזהרה חזק למיתון
בעוד **12-18 חודשים**.

למה זה עובד? לפי **השערת הציפיות** (Expectations Hypothesis), תשואה ל-10 שנים היא ממוצע
ציפיות לריבית קצרה ב-10 השנים הקרובות. אם השוק מצפה שהפד יוריד ריבית בעתיד (כי הוא צופה
האטה), הצד הארוך של העקום יורד מתחת לצד הקצר.

**שיעור הפגיעה ההיסטורי:** כל מיתון בארה"ב מאז 1960 קדמה לו היפוך עקום. היו רק 2 false
positives קלים – ב-1966 (האטה בלי מיתון רשמי) ובאמצע 1998 (היפוך קצר מאוד סביב משבר LTCM).
"""
)


def _yield_curve_fig() -> go.Figure:
    maturities = ["3M", "2Y", "5Y", "10Y", "30Y"]
    curves = {
        "🌱 התאוששות": [1.5, 2.0, 2.8, 3.4, 3.8],
        "🚀 אמצע מחזור": [3.0, 3.5, 4.0, 4.3, 4.6],
        "🔥 סוף מחזור": [5.2, 5.0, 4.7, 4.5, 4.4],
        "🧊 מיתון": [4.5, 3.5, 3.0, 2.8, 3.0],
    }
    fig = go.Figure()
    colors = ["#2ca02c", "#1f77b4", "#ff7f0e", "#d62728"]
    for (label, ys), color in zip(curves.items(), colors):
        fig.add_trace(
            go.Scatter(
                x=maturities,
                y=ys,
                name=label,
                mode="lines+markers",
                line=dict(color=color, width=3),
                marker=dict(size=8),
            )
        )
    fig.update_layout(
        template="plotly_dark",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        height=400,
        margin=dict(l=10, r=10, t=40, b=10),
        title="צורת עקום התשואות בכל שלב במחזור (אילוסטרציה)",
        xaxis_title="מח״מ",
        yaxis_title="תשואה (%)",
        dragmode="pan",
        legend=dict(orientation="h", y=-0.2),
    )
    return fig


st.plotly_chart(
    _yield_curve_fig(),
    use_container_width=True,
    config={"displayModeBar": False},
)

st.caption(
    "באמצע מחזור העקום תלול וחיובי. בסוף מחזור הוא משתטח ולעיתים מתהפך. במיתון, הפד מוריד ריבית והעקום חוזר להיות חיובי במהירות (steepening)."
)


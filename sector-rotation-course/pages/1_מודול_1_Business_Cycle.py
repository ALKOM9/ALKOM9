# ---------------------------- PMI ----------------------------

st.markdown("## 🏭 PMI – Purchasing Managers' Index")

st.markdown(
    """
ה-**ISM Manufacturing PMI** הוא סקר חודשי של מנהלי רכש בתעשייה האמריקאית. זה
**diffusion index** בסולם 0-100:

- **PMI > 50** → התרחבות (יותר מנהלים מדווחים על שיפור מאשר על הרעה).
- **PMI < 50** → התכווצות.
- **PMI < 45** → היסטורית, מיתון כבר בעיצומו.

למה זה אינדיקטור **מוביל**? מנהלי רכש מזמינים חומרי גלם שבועות לפני שהייצור מתחיל,
והייצור עצמו מתחיל חודשים לפני שהוא מופיע ב-GDP. הם רואים את הביקושים העתידיים לפני
כולם.

**תתי-הרכיבים** של ה-PMI לבד שווים זהב: **New Orders** (המוביל ביותר), **Production**
(מה קורה עכשיו), **Employment** (כיוון הגיוסים), **Inventories** (מלאים מצטברים = חולשה בביקוש).

> 📌 **הערה:** PMI הוא דאטה מורשה (ISM) ולא זמין דרך FRED. ב-**מודול 4** אנחנו משתמשים
> ב-**Industrial Production** (INDPRO) כתחליף ציבורי – קצת יותר מאוחר אבל בקורלציה גבוהה.
"""
)


from utils.page import bootstrap, page_end
from utils.quiz import render_quiz
import streamlit as st

bootstrap("מודול 6 – ברוקרים ועמלות")

st.markdown("## 6️⃣ מודול 6 – ברוקרים, ספרדים ועלויות אמיתיות")
st.caption("Market Maker / STP / ECN, ספרד קבוע מול משתנה, עמלות, swap, ועלות אמיתית של עסקה.")
st.divider()

st.markdown(
    """
### למה הברוקר מרוויח עליכם גם כשלא הרווחתם

ברוקר מט"ח לא עובד בחינם. הוא מרוויח על:

1. **ספרד** (תמיד) – ההפרש בין Bid ל-Ask.
2. **עמלה (Commission)** – סכום קבוע לכל $100,000 שנסחרים, בחלק מהמודלים.
3. **Swap (rollover)** – הפרשי הריבית בין שני המטבעות, במידה ופוזיציה הוחזקה לתוך הלילה.
4. **Slippage א-סימטרי** – הברוקר לוקח את הצד "הטוב" של ה-fill (ראינו במודול 4).
5. **תשלומי שיווק** (kickback) מ-LPs (אצל חלק מהברוקרים).

הבחירה במודל הברוקר משפיעה ישירות על העלות שלכם, **ובארביטראז' זה קריטי**.
"""
)

st.divider()

st.markdown("### 🏷️ שלושה סוגי ברוקרים")

st.markdown("**1. Market Maker (DD – Dealing Desk)**")
st.markdown(
    """
- הברוקר עצמו הוא ה-Counterparty שלכם. כשאתם קונים, הוא מוכר לכם *מתוך המלאי שלו*.
- ספרד בדרך כלל **קבוע** (1–3 pip ב-EUR/USD).
- בלי עמלה ישירה.
- **קונפליקט אינטרסים:** כשאתם מרוויחים, הברוקר מפסיד. ויש לו כלים להאט סדרים,
  להוסיף slippage, או לדחות ביצוע ברגעי תנודתיות.
- דוגמאות: רוב הברוקרים הקמעונאיים הגדולים, חלק מהפלטפורמות הישראליות.
"""
)

st.markdown("**2. STP (Straight Through Processing)**")
st.markdown(
    """
- מעביר את ההזמנה ישירות ל-LP חיצוני (בנק או ספק נזילות).
- ספרד **משתנה**, בדרך כלל 0.8–2 pip ב-EUR/USD.
- ייתכנו עמלות קטנות (כ-$3–$7 לכל $100k).
- פחות קונפליקט אינטרסים (הברוקר מרוויח על הספרד שלו, לא מההפסד שלכם).
- דוגמאות: ברוקרים אירופיים בינוניים.
"""
)

st.markdown("**3. ECN (Electronic Communications Network)**")
st.markdown(
    """
- אגרגציה של מספר ספקי נזילות – אתם רואים את ה-orderbook האמיתי.
- ספרד הצר ביותר (0.0–0.5 pip ב-EUR/USD בשעות שיא).
- **עמלה תמיד** – כ-$5–$10 לכל $100k (round-turn).
- הכי קרוב לתנאי המסחר של המוסדיים.
- מתאים יותר למסחר בנפחים גבוהים.
- דוגמאות: ברוקרי ECN בריטיים או אוסטרלים.
"""
)

st.info(
    "💡 **לארביטראז' תיאורטי, ECN הוא הבחירה היחידה.** Market Maker עם ספרד "
    "1.5 pip × 3 legs = כ-4.5 pip ספרד מצטבר. ECN עם ספרד 0.3 pip + עמלה = "
    "כ-1.5 pip מצטבר. ההפרש = כל הפערית הפוטנציאלית בעולם."
)

st.divider()

st.markdown("### 💰 Swap / Rollover")

st.markdown(
    """
**Swap** = הפרשי הריבית בין שני המטבעות בזוג, שמשולמים או נגבים מדי יום בשעה
22:00 שעון ניו יורק, על פוזיציות שהוחזקו לתוך הלילה.

דוגמה (USD/JPY ב-2025): ריבית USD כ-5%, ריבית JPY כ-0.5%.

- אם Long USD/JPY (יש לכם USD, אתם חייבים JPY) – **מקבלים** כ-4.5% / 365 ביום.
- אם Short USD/JPY (יש לכם JPY, אתם חייבים USD) – **משלמים** כ-4.5% / 365 ביום.

**בארביטראז' משולש שנמשך פחות משנייה Swap לא רלוונטי.** הוא הופך לבעיה רק אם
הברוקר תקוע, הסדר נשאר פתוח לתוך הלילה, או שאחד משלושת ה-legs לא נסגר.
"""
)

st.divider()

st.markdown("### 🧮 מחשבון עלויות מלא")

st.caption("הזינו את פרמטרי הברוקר שלכם לכל leg. המחשבון יציג עלות מצטברת ויאמר לכם אם הפערית התיאורטית עוברת את סף הרווחיות.")

col_b1, col_b2 = st.columns(2)
with col_b1:
    notional = st.number_input("גודל עסקה ($ לכל leg)", min_value=1000.0, value=100_000.0, step=1000.0)
    spread_per_leg = st.number_input("ספרד ממוצע (pip, לכל leg)", min_value=0.0, value=0.8, step=0.1)
with col_b2:
    commission_per_100k = st.number_input("עמלה ($ לכל $100k, round-turn)", min_value=0.0, value=7.0, step=0.5)
    slippage_per_leg = st.number_input("Slippage צפוי (pip, לכל leg)", min_value=0.0, value=0.3, step=0.1)

theoretical_edge_bp = st.slider(
    "פערית תיאורטית (basis points)",
    min_value=0.0, max_value=20.0, value=4.0, step=0.1,
)

spread_cost_bp = 1.5 * spread_per_leg
slippage_cost_bp = 3 * slippage_per_leg
commission_bp = ((commission_per_100k) / 100_000 * 10_000) * 3

total_cost_bp = spread_cost_bp + slippage_cost_bp + commission_bp
net_bp = theoretical_edge_bp - total_cost_bp

st.markdown("#### פירוט עלויות")
st.table(
    [
        {"רכיב": "ספרד (3 legs × 0.5)", "עלות (bp)": f"{spread_cost_bp:.2f}"},
        {"רכיב": "Slippage (3 legs)",   "עלות (bp)": f"{slippage_cost_bp:.2f}"},
        {"רכיב": "עמלות (3 legs)",      "עלות (bp)": f"{commission_bp:.2f}"},
        {"רכיב": "סך הכל עלויות",        "עלות (bp)": f"{total_cost_bp:.2f}"},
    ]
)

st.markdown(f"#### תוצאה: **{net_bp:+.2f} bp נטו** ({net_bp / 100:+.4f}%)")

if net_bp > 0.5:
    st.success(f"✅ הפערית מספיקה. רווח תיאורטי {net_bp:.2f} bp = {net_bp * notional / 10_000:.2f}$ לעסקה של {notional:,.0f}$.")
elif net_bp > -0.5:
    st.warning("⚠️ הפערית כמעט נאכלת על ידי העלויות. רווח או הפסד גבוליים – לא שווה את הסיכון.")
else:
    st.error(f"❌ העלויות גדולות מהפערית ב-{-net_bp:.2f} bp. הפסד ודאי.")

st.caption("💡 הזיזו את ה-slider של 'פערית תיאורטית' למעלה כדי לראות כמה הפערית צריכה להיות גדולה כדי שהעסקה תהיה רווחית.")

st.divider()

st.markdown("### ⚠️ עלויות נסתרות שלא הוזכרו")

st.markdown(
    """
- **עמלות משיכה (Withdrawal fees)** – חלק מהברוקרים גובים $25–$50 על כל משיכה.
  אם אתם רצים 3,000 עסקאות זה לא משמעותי. אם אתם מושכים פעמיים בחודש – שווה לבדוק.
- **דמי אי-פעילות (Inactivity fees)** – $10–$30 לחודש אם אין פעילות. רלוונטי אם
  הפסקתם באמצע.
- **המרת מטבע** – אם החשבון בשקלים וה-LPs במט"ח, יש המרה. עלות 0.3%–1%.
- **מס** – רווח הון, כ-25%. הברוקר לא גובה את זה, אבל זה משפיע על ה-P&L האמיתי שלכם.
"""
)


st.markdown("### 📏 5. גודל פוזיציה – כמה לסכן בעסקה")

st.markdown(
    """
גם אם הכל מסתדר טכנית, עדיין צריך להחליט **כמה כסף לסכן**. כללי אצבע
סטנדרטיים בעולם המסחר:

- **כלל ה-1%** – לא לסכן יותר מ-1% מההון בעסקה בודדת.
- **כלל ה-2%** – הגבול המקסימלי לטריידר אגרסיבי.
- **Risk of Ruin** – הסיכוי לאבד את כל ההון, בהינתן הסתברות הצלחה p וסיכון לעסקה r:
"""
)

st.latex(r"\text{RoR} \approx \left(\frac{1-p}{p}\right)^{N}")

st.markdown(
    """
- p = הסתברות לעסקה רווחית (אחרי עלויות).
- N = מספר ההפסדים שניתן לעמוד בהם (בדרך כלל N = 1 / risk_pct).

**בארביטראז' קמעונאי p לרוב נמוך מ-0.5** (כי העלויות בולעות את הפערית).
זה אומר ש-RoR מתקרב ל-100% – כלומר **תאבדו את כל ההון בנקודה כלשהי**
בהסתברות גבוהה.
"""
)

st.error(
    "⛔ **אם p < 0.5 אחרי עלויות, אסטרטגיה עם סיכון חיובי תוביל לפשיטת רגל "
    "בהסתברות 1.** זו תוצאה מתמטית, לא דעה. הימור נשאר הימור גם כשקוראים לו 'ארביטראז''."
)

st.divider()

st.markdown("### 🧮 מחשבון Risk of Ruin")

c1, c2, c3 = st.columns(3)
with c1:
    win_prob = st.slider("הסתברות הצלחה p", 0.30, 0.70, 0.45, 0.01)
with c2:
    risk_per_trade = st.slider("סיכון לעסקה (%)", 0.5, 10.0, 2.0, 0.5)
with c3:
    expected_trades = st.slider("מספר עסקאות צפויות", 10, 1000, 100, 10)

N_to_ruin = 100 / risk_per_trade
q = 1 - win_prob
if win_prob == 0.5:
    ror = 1.0 if expected_trades >= N_to_ruin else expected_trades / N_to_ruin
elif win_prob < 0.5:
    ror = min(1.0, (q / win_prob) ** N_to_ruin)
    if expected_trades < N_to_ruin * 3:
        ror = min(ror, expected_trades / (N_to_ruin * 3))
else:
    ror = (q / win_prob) ** N_to_ruin

ror_pct = ror * 100

mcol1, mcol2 = st.columns(2)
mcol1.metric("Risk of Ruin (מוערך)", f"{ror_pct:.1f}%")
mcol2.metric("הפסדים רצופים עד פשיטת רגל", f"{int(N_to_ruin)}")

if ror_pct > 50:
    st.error(f"❌ סיכון פשיטת רגל גבוה ({ror_pct:.0f}%). אסטרטגיה זו אינה בת קיימא.")
elif ror_pct > 20:
    st.warning(f"⚠️ סיכון משמעותי לפשיטת רגל ({ror_pct:.0f}%). שקלו להקטין את הסיכון לעסקה.")
elif ror_pct > 5:
    st.info(f"📐 סיכון מתון לפשיטת רגל ({ror_pct:.0f}%).")
else:
    st.success(f"✅ סיכון נמוך ({ror_pct:.1f}%) – אבל זה דורש Edge אמיתי (p > 0.55).")

st.caption("💡 הזיזו את p ל-0.45 ואת הסיכון ל-5% – תראו שהסיכוי לאבד את הכל מטפס לעשרות אחוזים תוך 100 עסקאות.")


st.markdown("### 🧠 Last-Look ו-asymmetric slippage")

st.markdown(
    """
ספק נזילות (LP) שמצטט לך מחיר ב-feed הוא **לא מחויב** למכור באותו מחיר.
ברוב הפלטפורמות יש **"last look"** – שבריר שנייה שבו ה-LP מסתכל על ה-order שלך,
ובוחר אם לאשר אותו במחיר המקורי, לדחות, או "rejcect-and-requote" במחיר חדש.

**מדוע זה רלוונטי לארביטראז':**
1. אם המחיר זז לטובתך (הפערית גדלה) – הוא ידחה / יחזיר מחיר מעודכן.
2. אם המחיר זז לרעתך – הוא יבצע (כי הוא מרוויח).

זה נקרא **asymmetric slippage**. בפועל, רוב הפערים שראית ב-feed הם **מחירי
פרסום** ולא מחירים שתבצע בהם. רגולציה (FCA, NFA) מצמצמת את זה אבל לא מבטלת.
"""
)


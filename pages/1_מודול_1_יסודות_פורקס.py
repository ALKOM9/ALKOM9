st.markdown("### 📋 איך קוראים ציטוט")

st.markdown(
    """
זוג נכתב כך: **EUR/USD = 1.0850**

- **EUR** = ה-**Base** (המטבע הבסיסי, זה שמשמאל).
- **USD** = ה-**Quote** (מטבע הציטוט, זה שמימין).
- **1.0850** = כמה יחידות של ה-Quote נדרשות כדי לקנות **יחידה אחת** של ה-Base.

במילים פשוטות: 1 יורו = 1.0850 דולר.

אם המחיר עולה ל-1.0900 – היורו (Base) התחזק מול הדולר (Quote).
אם הוא יורד ל-1.0800 – היורו נחלש.
"""
)

st.info("💡 **דרך לזכור:** המטבע משמאל הוא תמיד זה שנקנה, המטבע מימין הוא זה שמשולם. ב-EUR/USD קונים יורו ומשלמים בדולרים.")

st.divider()


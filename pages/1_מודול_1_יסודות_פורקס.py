st.markdown("### 📏 Pip ו-Pipette")

st.markdown(
    """
- **Pip** (קיצור של "Percentage In Point") – הספרה הרביעית אחרי הנקודה ברוב הזוגות.
  אם EUR/USD זז מ-1.0850 ל-1.0851 – זוהי תנועה של **1 pip**.
- **Pipette** – הספרה החמישית, עשירית של pip. ברוקרים מודרניים מצטטים ב-5 ספרות.
- **חריג חשוב: זוגות עם ין יפני (JPY).** שם ה-pip הוא הספרה השנייה אחרי הנקודה.
  USD/JPY מ-149.50 ל-149.51 = **1 pip**.

**שווי pip בדולרים** (בחשבון שהוא Base-USD, לוט סטנדרטי של 100,000 יחידות):

- ב-Major (EUR/USD, GBP/USD וכו'): 1 pip ≈ **10$**.
- ב-Mini lot (10,000 יחידות): ≈ **1$**.
- ב-Micro lot (1,000 יחידות): ≈ **0.10$**.
"""
)

